fun main() {
    var i: Int = 10
    while (i >= 1) {
        println(i)
        i--
    }

    repeat(5) {
        println("Hello World")
    }
}

/*
  Dùng while khi không bắt buộc biết trước số lần lặp, phụ thuộc vào một điều kiện
  Dùng repeat khi đã biết trước số lần muốn thực hiện 
